/* SOLO LECTURA EN ORACLE.
   Busca filas que cumplen filtros de entrada de la version MSSQL revisada.
   Ajustar FechaDestino al dia del servidor MSSQL cuando se vaya a probar.
   No modifica fechas, no ejecuta procesos ni consume NEXTVAL.
   Muestra hasta 50 filas para elegir un lote completo por grupo DESPUES.
   Los indicadores de faltantes no sustituyen la validacion fiscal/generador.
*/
WITH Parametros AS (
 SELECT DATE '2026-10-29' FechaDestino,30 Dias FROM DUAL
)
SELECT
 C.ASIGNACION_ID,C.FOLIO_ID,C.FACTURA,C.NOTA_VENTA,C.RFC,
 C.CLIENTE_SAP,C.ACCNT_ID,C.VIA_PAGO,C.STATUS,
 C.IMPORTE,C.SALDO_ANTERIOR,C.NUMERO_PAGO,C.UUID_VENTA,
 TO_CHAR(C.FECHA_PROCESO,'YYYY-MM-DD HH24:MI:SS') FECHA_PROCESO,
 TO_CHAR(C.FECHA_PAGO,'YYYY-MM-DD HH24:MI:SS') FECHA_PAGO,
 C.ASIGNACION_CENTRAL,C.BANCO_NOMBRE,C.BANCO_NUM_CUENTA,C.CTRO,
 CASE WHEN EXISTS(SELECT 1 FROM T3.CFDI_AGRUPACION_PAGO A
                  WHERE A.ASIGNACION_ID=C.ASIGNACION_ID)
      THEN 'YA TIENE RELACION: REVISAR ANTES DE MIGRAR' ELSE 'SIN RELACION' END AGRUPACION_PREVIA,
 CASE WHEN C.ACCNT_ID IS NULL THEN 'NULL: REVISAR MAX DEL GRUPO'
      WHEN C.ACCNT_ID='Contado' THEN 'CONTADO: EXCLUIDO POR LIBERADOR MSSQL'
      ELSE 'INFORMADO' END REVISION_ACCNT,
 (SELECT COUNT(*) FROM T3.CFDI_DOCUMENTOS D WHERE D.NOTA_VENTA=C.NOTA_VENTA) DOCUMENTOS_VENTA,
 (SELECT COUNT(*) FROM T3.REGISTRO_FISCAL R WHERE R.FACTURA=C.FACTURA) CABECERAS_FISCALES,
 (SELECT COUNT(*) FROM T3.REGISTRO_FISCAL_DETALLE D WHERE D.FACTURA=C.FACTURA) DETALLES_FISCALES,
 (SELECT COUNT(*) FROM T3.REGISTRO_FISCAL R
  JOIN T3.CFDI_USOCFDI_CLIENTE U ON U.CLIENTE_SAP=R.CLIENTE_SAP
  WHERE R.FACTURA=C.FACTURA) CABECERAS_CON_USOCFDI,
 (SELECT COUNT(*) FROM T3.MOV_CLIENTE M WHERE M.CLIENTE_SAP=C.CLIENTE_SAP) FILAS_CLIENTE,
 (SELECT COUNT(*) FROM T3.CFDI_COBRANZA X WHERE X.ASIGNACION_ID=C.ASIGNACION_ID) FILAS_POR_ASIGNACION
FROM T3.CFDI_COBRANZA C CROSS JOIN Parametros P
WHERE C.FECHA_ENVIO IS NULL
 AND C.CREATED_BY<>'INTERFACE'
 AND C.VIA_PAGO NOT IN ('01','CM','AI')
 AND NVL(C.STATUS,'1') NOT IN ('Debit Note','Canc Pago')
 AND C.FECHA_PROCESO>P.FechaDestino-P.Dias
 AND C.RFC<>'XAXX010101000'
 AND NOT EXISTS(SELECT 1 FROM T3.WA_FACTORAJE F WHERE F.FACTURA=C.FACTURA)
ORDER BY C.FECHA_PROCESO DESC,C.ASIGNACION_ID
FETCH FIRST 50 ROWS ONLY;

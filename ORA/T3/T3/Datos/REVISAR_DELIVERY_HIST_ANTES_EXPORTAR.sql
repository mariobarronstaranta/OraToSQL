/* Solo lectura. Mismo filtro de la exportacion. Revisar antes de cargar.
   Cada indicador cuenta filas, no caracteres. Todos deberian ser cero para
   exportar sin colisiones, cantidades no representables ni fechas requeridas
   ausentes. No corrige ni excluye silenciosamente registros.
   No modifica registros ni hace COMMIT/ROLLBACK.
*/
WITH D AS (
    SELECT H.*,
           DELIVERY || CHR(0) || PURCHASEORDER || CHR(0) || DELIVERYTYPE || CHR(0) ||
           STATUS || CHR(0) || PLANT || CHR(0) || SHIPPINGPOINT || CHR(0) ||
           SOLDTOPARTY || CHR(0) || SLOC || CHR(0) || SHIPTOPARTY || CHR(0) ||
           SHIPTOPARTYNAME || CHR(0) || MATERIAL || CHR(0) || MATERIALNAME || CHR(0) ||
           UNITMEASURE || CHR(0) || SHIPTOPARTYLOC || CHR(0) || SOCIEDAD AS TEXTOS
    FROM T3.DELIVERY_HIST H
    WHERE CREATED>DATE '2026-07-31'
)
SELECT COUNT(*) FILAS_A_EXPORTAR,
       COUNT(CASE WHEN INSTR(TEXTOS,'~|~')>0 THEN 1 END) CON_DELIMITADOR_NUEVO,
       COUNT(CASE WHEN INSTR(TEXTOS,CHR(13))>0 OR INSTR(TEXTOS,CHR(10))>0 THEN 1 END) CON_SALTOS_DE_LINEA,
       COUNT(CASE WHEN DELIVERYDATE IS NULL THEN 1 END) SIN_DELIVERYDATE,
       COUNT(CASE WHEN ABS(ROUND(QUANTITY,3))>99999999999.999 THEN 1 END) CANTIDAD_FUERA_DE_RANGO,
       COUNT(CASE WHEN QUANTITY<>ROUND(QUANTITY,3) THEN 1 END) CANTIDAD_MAS_DE_3_DECIMALES,
       COUNT(CASE WHEN LENGTH(DELIVERY)>10 OR LENGTH(PURCHASEORDER)>20 OR LENGTH(DELIVERYTYPE)>4
                        OR LENGTH(STATUS)>10 OR LENGTH(PLANT)>4 OR LENGTH(SHIPPINGPOINT)>4
                        OR LENGTH(SOLDTOPARTY)>20 OR LENGTH(SLOC)>10 OR LENGTH(SHIPTOPARTY)>30
                        OR LENGTH(SHIPTOPARTYNAME)>60 OR LENGTH(MATERIAL)>20 OR LENGTH(MATERIALNAME)>50
                        OR LENGTH(UNITMEASURE)>10 OR LENGTH(SHIPTOPARTYLOC)>40 OR LENGTH(SOCIEDAD)>4
                  THEN 1 END) TEXTO_EXCEDE_LONGITUD_DESTINO
FROM D;

-- Confirmar el dato original de la delivery que fallo con el separador '|'.
-- Un | dentro de SHIPTOPARTYNAME se conserva al usar ~|~ como terminador.
SELECT DELIVERY,SHIPTOPARTYNAME,MATERIAL,MATERIALNAME,QUANTITY,UNITMEASURE,SOCIEDAD
FROM T3.DELIVERY_HIST
WHERE CREATED>DATE '2026-07-31' AND DELIVERY='2656613453'
ORDER BY MATERIAL;

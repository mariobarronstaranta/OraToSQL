WHERE EXISTS (
 SELECT 1 FROM T3.REGISTRO_FISCAL RF
 WHERE RF.CLIENTE_SAP=U.CLIENTE_SAP
 AND RF.FACTURA IN ('V0225-134949','V0822-105802','V0179-67553','V0440-70133')
);


-- IDs originales identificados en CFDI_AGRUPACION_PAGO.txt.
SELECT * FROM T3.CFDI_AGRUPACION_CTRL
WHERE AGRUPACION IN (529120,529096,529050,529179);

-- Obtener todo el detalle de cada grupo, no solo las cuatro asignaciones.
SELECT * FROM T3.CFDI_AGRUPACION_PAGO
WHERE AGRUPACION IN (529120,529096,529050,529179)
ORDER BY AGRUPACION, ASIGNACION_ID;


WHERE NOTA_VENTA IN ('529120','529096','529050','529179',
                    '529120.00','529096.00','529050.00','529179.00');

SELECT * FROM T3.CFDI_DOCUMENTOS_ENVIAR
WHERE NOTA_VENTA IN ('529120','529096','529050','529179',
                    '529120.00','529096.00','529050.00','529179.00');


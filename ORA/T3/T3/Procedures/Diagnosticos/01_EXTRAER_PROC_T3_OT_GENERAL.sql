PROMPT === 02. OBJETOS VISIBLES Y ESTADO ===
SELECT OWNER,OBJECT_NAME,OBJECT_TYPE,STATUS,LAST_DDL_TIME
FROM ALL_OBJECTS
WHERE OWNER='T3'
  AND OBJECT_NAME IN ('PROC_T3_OT_GENERAL','PROC_V40_GENERAR_OTROS',
      'PROC_CFDI_GENERAR_OTROS','WA_ERR_INVOICE_PAYMETHOD',
      'GET_SAT_CLAVEPRODUCTO','FN_NUM_TO_CHAR_CFDI')
  AND OBJECT_TYPE IN ('PROCEDURE','FUNCTION','SYNONYM')
ORDER BY OBJECT_NAME,OBJECT_TYPE;

PROMPT === 03. FUENTE COMPLETO CON NUMEROS DE LINEA ===
PROMPT Se incluyen nombres alternativos del generador; los ausentes no producen filas.
PROMPT Si TEXT dice wrapped, el fuente requiere su version original sin envolver.
SELECT OWNER,NAME,TYPE,LINE,TEXT
FROM ALL_SOURCE
WHERE OWNER='T3'
  AND NAME IN ('PROC_T3_OT_GENERAL','PROC_V40_GENERAR_OTROS',
      'PROC_CFDI_GENERAR_OTROS','WA_ERR_INVOICE_PAYMETHOD',
      'GET_SAT_CLAVEPRODUCTO','FN_NUM_TO_CHAR_CFDI')
  AND TYPE IN ('PROCEDURE','FUNCTION')
ORDER BY NAME,TYPE,LINE;

PROMPT === 04. DEPENDENCIAS PARA IDENTIFICAR EL GENERADOR REAL ===
SELECT OWNER,NAME,TYPE,REFERENCED_OWNER,REFERENCED_NAME,REFERENCED_TYPE
FROM ALL_DEPENDENCIES
WHERE OWNER='T3'
  AND NAME IN ('PROC_T3_OT_GENERAL','PROC_V40_GENERAR_OTROS',
      'PROC_CFDI_GENERAR_OTROS','WA_ERR_INVOICE_PAYMETHOD','GET_SAT_CLAVEPRODUCTO')
ORDER BY NAME,REFERENCED_OWNER,REFERENCED_TYPE,REFERENCED_NAME;

PROMPT === 05. SINONIMOS DEL COORDINADOR O GENERADOR ===
SELECT OWNER,SYNONYM_NAME,TABLE_OWNER,TABLE_NAME,DB_LINK
FROM ALL_SYNONYMS
WHERE OWNER IN ('T3','PUBLIC')
  AND SYNONYM_NAME IN ('PROC_T3_OT_GENERAL','PROC_V40_GENERAR_OTROS','PROC_CFDI_GENERAR_OTROS')
ORDER BY OWNER,SYNONYM_NAME;

PROMPT === 06. COBERTURA DE FUENTES ===
PROMPT Cero lineas no prueba ausencia del objeto: revisar permisos, sinonimos o instancia.
SELECT N.NOMBRE,COUNT(S.LINE) AS LINEAS_VISIBLES
FROM (
    SELECT 'PROC_T3_OT_GENERAL' NOMBRE FROM DUAL
    UNION ALL SELECT 'PROC_V40_GENERAR_OTROS' FROM DUAL
    UNION ALL SELECT 'PROC_CFDI_GENERAR_OTROS' FROM DUAL
    UNION ALL SELECT 'WA_ERR_INVOICE_PAYMETHOD' FROM DUAL
    UNION ALL SELECT 'GET_SAT_CLAVEPRODUCTO' FROM DUAL
    UNION ALL SELECT 'FN_NUM_TO_CHAR_CFDI' FROM DUAL
) N
LEFT JOIN ALL_SOURCE S ON S.OWNER='T3' AND S.NAME=N.NOMBRE
    AND S.TYPE IN ('PROCEDURE','FUNCTION')
GROUP BY N.NOMBRE
ORDER BY N.NOMBRE;


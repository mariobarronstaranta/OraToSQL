  CREATE OR REPLACE EDITIONABLE TRIGGER "T3"."TRG_COBRANZA" 
 AFTER UPDATE OR DELETE ON T3.CFDI_COBRANZA
 REFERENCING OLD AS OLD NEW AS NEW
 FOR EACH ROW
DECLARE
   sUserName                 VARCHAR2(020) ;
   sLog_Action               VARCHAR2(010) ; 
   nLogging                  NUMBER(03)    ;
   sOLD_FOLIO_ID             VARCHAR2(30)  ;
   dOLD_FECHA_ASIGNACION     DATE          ;
   nOLD_IMPORTE              NUMBER(16,2)  ;
   sOLD_FACTURA              VARCHAR2(30)  ;
   sOLD_RFC                  VARCHAR2(15)  ;
   sOLD_VIA_PAGO             VARCHAR2(04)  ;
   sOLD_NOTA_CREDITO         VARCHAR2(30)  ;
   sNEW_FOLIO_ID             VARCHAR2(30)  ;
   dNEW_FECHA_ASIGNACION     DATE          ;
   nNEW_IMPORTE              NUMBER(16,2)  ;
   sNEW_FACTURA              VARCHAR2(30)  ;
   sNEW_RFC                  VARCHAR2(15)  ;
   sNEW_VIA_PAGO             VARCHAR2(04)  ;
   sNEW_NOTA_CREDITO         VARCHAR2(30)  ;
BEGIN   
    IF INSERTING THEN
       sLog_Action := 'Insert'  ;
    ELSIF UPDATING THEN
       sLog_Action := 'Update'  ;
    ELSIF DELETING THEN
       sLog_Action := 'Delete'  ;
    ELSE
       sLog_Action := 'Unknown' ;
    END IF ;
    SELECT User INTO sUserName FROM DUAL ;
    nLogging := 0 ;
--
    sOLD_FOLIO_ID          := NULL ;
    dOLD_FECHA_ASIGNACION  := NULL ;
    nOLD_IMPORTE           := NULL ;
    sOLD_FACTURA           := NULL ;
    sOLD_RFC               := NULL ;
    sOLD_VIA_PAGO          := NULL ;
    sOLD_NOTA_CREDITO      := NULL ;
    sNEW_FOLIO_ID          := NULL ;
    dNEW_FECHA_ASIGNACION  := NULL ;
    nNEW_IMPORTE           := NULL ;
    sNEW_FACTURA           := NULL ;
    sNEW_RFC               := NULL ;
    sNEW_VIA_PAGO          := NULL ;
    sNEW_NOTA_CREDITO      := NULL ;
--    
    IF ( NVL( :NEW.FOLIO_ID, 'NULO' ) != NVL( :OLD.FOLIO_ID, 'NULO' ) ) THEN
       nLogging              := nLogging + 1       ;
       sNEW_FOLIO_ID         := :NEW.FOLIO_ID      ;
       sOLD_FOLIO_ID         := :OLD.FOLIO_ID      ;
    END IF ;
    IF ( NVL( :NEW.FECHA_ASIGNACION, TRUNC( SYSDATE ) ) != NVL( :OLD.FECHA_ASIGNACION, TRUNC( SYSDATE ) ) ) THEN
       nLogging              := nLogging + 1          ;
       dNEW_FECHA_ASIGNACION := :NEW.FECHA_ASIGNACION ;
       dOLD_FECHA_ASIGNACION := :OLD.FECHA_ASIGNACION ;
    END IF ;
    IF ( NVL( :NEW.IMPORTE, 0 ) != NVL( :OLD.IMPORTE, 0 ) ) THEN
       nLogging              := nLogging + 1       ;
       nNEW_IMPORTE          := :NEW.IMPORTE       ;
       nOLD_IMPORTE          := :OLD.IMPORTE       ;
    END IF ; 
    IF ( NVL( :NEW.FACTURA, 'NULO' ) != NVL( :OLD.FACTURA, 'NULO' ) ) THEN
       nLogging              := nLogging + 1       ;
       sNEW_FACTURA          := :NEW.FACTURA       ;
       sOLD_FACTURA          := :OLD.FACTURA       ;
    END IF ;
    IF ( NVL( :NEW.RFC, 'NULO' ) != NVL( :OLD.RFC, 'NULO' ) ) THEN
       nLogging              := nLogging + 1       ;
       sNEW_RFC              := :NEW.RFC           ;
       sOLD_RFC              := :OLD.RFC           ;
    END IF ;
    IF ( NVL( :NEW.VIA_PAGO, 'NULO' ) != NVL( :OLD.VIA_PAGO, 'NULO' ) ) THEN
       nLogging              := nLogging + 1       ;
       sNEW_VIA_PAGO         := :NEW.VIA_PAGO      ;
       sOLD_VIA_PAGO         := :OLD.VIA_PAGO      ;
    END IF ;
    IF ( NVL( :NEW.NOTA_CREDITO, 'NULO' ) != NVL( :OLD.NOTA_CREDITO, 'NULO' ) ) THEN
       nLogging              := nLogging + 1       ;
       sNEW_NOTA_CREDITO     := :NEW.NOTA_CREDITO  ;
       sOLD_NOTA_CREDITO     := :OLD.NOTA_CREDITO  ;    
    END IF ;
--    
    IF ( nLogging > 0 ) THEN
       INSERT INTO T3.CFDI_COBRANZA_LOG 
          ( Fecha, Usuario, Action, Usuario_Red, IP, Terminal,
            OLD_FOLIO_ID         , OLD_FECHA_ASIGNACION , OLD_IMPORTE          ,
            OLD_FACTURA          , OLD_RFC              , OLD_VIA_PAGO         , OLD_NOTA_CREDITO     ,
            NEW_FOLIO_ID         , NEW_FECHA_ASIGNACION , NEW_IMPORTE          ,
            NEW_FACTURA          , NEW_RFC              , NEW_VIA_PAGO         , NEW_NOTA_CREDITO      ) 
       VALUES
          ( SYSDATE , sUsername, sLog_Action,
            SYS_CONTEXT( 'USERENV' , 'OS_USER'    ), 
            SYS_CONTEXT( 'USERENV' , 'IP_ADDRESS' ),
            SYS_CONTEXT( 'USERENV' , 'HOST'       ), 
            sOLD_FOLIO_ID        , dOLD_FECHA_ASIGNACION, nOLD_IMPORTE         ,
            sOLD_FACTURA         , sOLD_RFC             , sOLD_VIA_PAGO        , sOLD_NOTA_CREDITO    ,
            sNEW_FOLIO_ID        , dNEW_FECHA_ASIGNACION, nNEW_IMPORTE         ,
            sNEW_FACTURA         , sNEW_RFC             , sNEW_VIA_PAGO        , sNEW_NOTA_CREDITO     ) ;
    END IF ;            
--    
END TRG_COBRANZA ;

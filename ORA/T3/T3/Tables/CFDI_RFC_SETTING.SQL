  CREATE OR REPLACE EDITIONABLE TRIGGER "T3"."TRG_LOGGING_RFC_SETTING" 
 AFTER INSERT OR UPDATE OR DELETE ON T3.CFDI_RFC_Setting
 REFERENCING OLD AS OLD NEW AS NEW
 FOR EACH ROW
DECLARE
   sUserName     VARCHAR2(020) ;
   sLog_Action   VARCHAR2(010) ; 
   nLogging      NUMBER(02)    ;
   sNew_RFC      VARCHAR2(030) ;
   sNew_Param    VARCHAR2(030) ;   
   sNew_Valor    VARCHAR2(150) ;   
   sOld_RFC      VARCHAR2(030) ;
   sOld_Param    VARCHAR2(030) ;   
   sOld_Valor    VARCHAR2(150) ;   
BEGIN   
    IF INSERTING THEN
       sLog_Action := 'Insert'  ;
    ELSIF UPDATING THEN
       sLog_Action := 'Update'  ;
    ELSIF DELETING THEN
       sLog_Action := 'Delete'  ;
    ELSE
       sLog_Action := 'Unknown' ;
    END IF ;
    SELECT User INTO sUserName FROM DUAL ;
    nLogging    := 1 ;
    sNew_RFC    := :NEW.RFC       ;
    sNew_Param  := :NEW.PARAMETRO ;
    sNew_Valor  := :NEW.VALOR     ;
    sOld_RFC    := :OLD.RFC       ;
    sOld_Param  := :OLD.PARAMETRO ;
    sOld_Valor  := :OLD.VALOR     ;
--    
    IF ( nLogging > 0 ) THEN
       INSERT INTO T3.CFDI_RFC_Setting_Log 
          ( Fecha, Usuario, Action, Usuario_Red, IP, Terminal,
            New_RFC, New_Parametro, New_Valor, Old_RFC, Old_Parametro, Old_Valor )            
       VALUES
          ( SYSDATE , sUsername, sLog_Action,
            SYS_CONTEXT( 'USERENV' , 'OS_USER'    ), 
            SYS_CONTEXT( 'USERENV' , 'IP_ADDRESS' ),
            SYS_CONTEXT( 'USERENV' , 'HOST'       ), 
            sNew_RFC, sNew_Param, sNew_Valor, sOld_RFC, sOld_Param, sOld_Valor ) ;   
    END IF ;            
--    
END TRG_LOGGING_RFC_SETTING ;
/
ALTER TRIGGER "T3"."TRG_LOGGING_RFC_SETTING" ENABLE;



SELECT 'FACTURA,FECHA_FACTURA,TIPO_DOCTO,ENTREGA,TOTAL'
   FROM DUAL
UNION ALL
SELECT RFD.FACTURA 	|| ',' || 
TO_CHAR(RF.FECHA_FACTURA,'DD/MM/YYYY') 	|| ',' || 
RF.TIPO_DOCTO 		|| ',' || 
RF.ENTREGA 		|| ',' ||
SUM(NVL(RFD.VALOR_SUBT,0)+ NVL(RFD.VALOR_IVA,0) +NVL(RFD.ENVIO_SUBT,0) + NVL(RFD.ENVIO_IVA,0) + NVL(RFD.CREDITO_SUBT,0) + NVL(RFD.CREDITO_IVA,0))   AS TOTAL 
FROM T3.REGISTRO_FISCAL_DETALLE RFD, T3.REGISTRO_FISCAL RF
WHERE RFD.FACTURA = RF.FACTURA
AND RF.FECHA_FACTURA >= TO_DATE ('01/02/2023','DD/MM/YYYY')
AND RF.FECHA_FACTURA < TO_DATE ('01/03/2023','DD/MM/YYYY')
AND RF.TIPO_DOCTO IN ('C003','C005', 'C004','C006', 'C025')
AND RF.STATUS != 'Cancelled'
GROUP BY RFD.FACTURA, RF.FECHA_FACTURA, RF.TIPO_DOCTO, RF.ENTREGA;





WHERE L.CREATED >= CONVERT(DATETIME2,'2026-10-23T17:15:22')
  AND (L.JOB_PID = '26516078' OR EXISTS
       (SELECT 1 FROM @Documentos AS D
        WHERE D.Referencia COLLATE DATABASE_DEFAULT = L.REFERENCE COLLATE DATABASE_DEFAULT))
ORDER BY L.CREATED, L.QUEUE_NAME;

SELECT '06_VERSION_COORDINADOR' AS Seccion, O.modify_date,
       M.execute_as_principal_id, LEN(M.definition) AS LongitudDefinicion
FROM sys.objects AS O
LEFT JOIN sys.sql_modules AS M ON M.object_id = O.object_id
WHERE O.object_id = OBJECT_ID(N'EAI_OWNER.RECV_INVOICE_INTERCOMPANY', N'P');

DECLARE @Def NVARCHAR(MAX) = OBJECT_DEFINITION(OBJECT_ID(N'EAI_OWNER.RECV_INVOICE_INTERCOMPANY',N'P'));
;WITH Segmentos AS
(
    SELECT 1 AS Numero WHERE @Def IS NOT NULL
    UNION ALL
    SELECT Numero+1 FROM Segmentos WHERE Numero*200 < LEN(@Def)
)
SELECT '07_DEFINICION_COORDINADOR' AS Seccion, Numero AS Segmento,
       SUBSTRING(@Def,(Numero-1)*200+1,200) AS Texto
FROM Segmentos ORDER BY Numero OPTION (MAXRECURSION 0);

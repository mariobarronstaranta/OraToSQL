SELECT '01_AMBIENTE' AS Seccion, @@SERVERNAME AS Servidor,
       DB_NAME() AS BaseActual, SYSDATETIMEOFFSET() AS FechaCaptura;

SELECT '02_RECEPCION_Y_TEMPORALES' AS Seccion,
       D.RowIdEsperado, D.Referencia AS ReferenciaEsperada,
       R.ROW_ID, R.CREATED, R.PROCESSED, R.REFERENCE, R.STATUS,
       H.ReferenceID, H.FacturaSAP, H.DeliveryType, H.CompanyCode,
       H.PedidoV3, H.Procesado AS TemporalProcesado,
       CASE WHEN R.ROW_ID IS NULL THEN N'NO EXISTE ROW_ID'
            WHEN R.REFERENCE COLLATE DATABASE_DEFAULT <> D.Referencia COLLATE DATABASE_DEFAULT
                 OR R.REFERENCE IS NULL THEN N'REVISAR REFERENCIA'
            ELSE N'ROW_ID Y REFERENCIA COINCIDEN' END AS Identidad,
       CASE WHEN R.CREATED > DATEADD(DAY,-5,CONVERT(DATETIME2(0),CONVERT(DATE,SYSDATETIME())))
            THEN 1 ELSE 0 END AS DentroVentanaCincoDiasLocal
FROM @Documentos AS D
LEFT JOIN EAI_OWNER.MX_RECEIVE_MESSAGE_LOG AS R
  ON R.ROW_ID COLLATE DATABASE_DEFAULT = D.RowIdEsperado COLLATE DATABASE_DEFAULT
LEFT JOIN EAI_OWNER.TMP_DOCUMENT_HEADER AS H
  ON H.ReferenceID COLLATE DATABASE_DEFAULT = D.Referencia COLLATE DATABASE_DEFAULT
ORDER BY D.Referencia;

-- OTROS usa FacturaSAP como folio; no ejecuta generacion ni modificaciones.
SELECT '03_SALIDAS_OTROS' AS Seccion, D.Referencia,
       G.FACTURA, G.FECHA_TRN, G.FECHA_PROC_BATMD,
       (SELECT COUNT_BIG(*) FROM T3.OTROS_DETALLE AS X
        WHERE X.FACTURA COLLATE DATABASE_DEFAULT = G.FACTURA COLLATE DATABASE_DEFAULT) AS Detalles,
       (SELECT COUNT_BIG(*) FROM T3.OTROS_CONDICIONES AS X
        WHERE X.FACTURA COLLATE DATABASE_DEFAULT = G.FACTURA COLLATE DATABASE_DEFAULT) AS Condiciones
FROM @Documentos AS D
INNER JOIN EAI_OWNER.TMP_DOCUMENT_HEADER AS H
  ON H.ReferenceID COLLATE DATABASE_DEFAULT = D.Referencia COLLATE DATABASE_DEFAULT
LEFT JOIN T3.OTROS_GENERAL AS G
  ON G.FACTURA COLLATE DATABASE_DEFAULT = H.FacturaSAP COLLATE DATABASE_DEFAULT
WHERE H.DeliveryType NOT IN ('C020','C021','C022')
ORDER BY D.Referencia;

-- PREVENTA recibe ReferenceID en ENTREGA; el folio puede ser distinto del SAP.
SELECT '04_SALIDAS_PREVENTA' AS Seccion, D.Referencia,
       G.FACTURA, G.ENTREGA, G.FECHA_TRN, G.FECHA_PROC_BATMD,
       (SELECT COUNT_BIG(*) FROM T3.PREVENTA_DETALLE AS X
        WHERE X.FACTURA COLLATE DATABASE_DEFAULT = G.FACTURA COLLATE DATABASE_DEFAULT) AS Detalles,
       (SELECT COUNT_BIG(*) FROM T3.PREVENTA_CONDICIONES AS X
        WHERE X.FACTURA COLLATE DATABASE_DEFAULT = G.FACTURA COLLATE DATABASE_DEFAULT) AS Condiciones
FROM @Documentos AS D
INNER JOIN EAI_OWNER.TMP_DOCUMENT_HEADER AS H
  ON H.ReferenceID COLLATE DATABASE_DEFAULT = D.Referencia COLLATE DATABASE_DEFAULT
LEFT JOIN T3.PREVENTA_GENERAL AS G
  ON G.ENTREGA COLLATE DATABASE_DEFAULT = D.Referencia COLLATE DATABASE_DEFAULT
WHERE H.DeliveryType IN ('C020','C021','C022')
ORDER BY D.Referencia;

SELECT '05_ERRORES_DOCUMENTOS' AS Seccion,

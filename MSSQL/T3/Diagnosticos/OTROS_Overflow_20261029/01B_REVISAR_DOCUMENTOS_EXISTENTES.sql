   No borrar documentos ni ejecutar reenvio/generacion con esta consulta.
*/
USE [T3QA]; SET NOCOUNT ON;
DECLARE @F table(Factura varchar(30) COLLATE DATABASE_DEFAULT PRIMARY KEY);
INSERT @F VALUES('1658507150'),('1658507151'),('1658516300'),('1658516520'),('1658520040'),('1658520050');
SELECT @@SERVERNAME Servidor,DB_NAME() BaseDatos,GETDATE() Captura;
SELECT '01_DOCUMENTO_EXISTENTE' Seccion,D.*,
 CASE WHEN NULLIF(LTRIM(RTRIM(D.Folio_Fiscal)),'') IS NOT NULL
       OR D.Fecha_Timbre IS NOT NULL OR D.Fecha_Envio IS NOT NULL
       OR D.Fecha_Confirmacion IS NOT NULL
       OR NULLIF(LTRIM(RTRIM(D.Id_Envio)),'') IS NOT NULL
       OR NULLIF(LTRIM(RTRIM(D.Id_Confirmacion)),'') IS NOT NULL
      THEN 'CON EVIDENCIA DE ENVIO/TIMBRADO: PRESERVAR Y CONCILIAR'
      ELSE 'SIN ESAS MARCAS: REVISAR ORIGEN/STATUS ANTES DE REEMPLAZAR' END Revision
FROM T3.CFDI_DOCUMENTOS D JOIN @F F ON F.Factura=D.Nota_Venta
ORDER BY D.Nota_Venta,D.Fecha_Liberacion;
SELECT '02_LAYOUTS' Seccion,E.Nota_Venta,DATALENGTH(E.Informacion) BytesLayout
FROM T3.CFDI_DOCUMENTOS_ENVIAR E JOIN @F F ON F.Factura=E.Nota_Venta;
SELECT '03_HISTORIAL_REPROCESO' Seccion,R.*
FROM T3.CFDI_REPROCESO R JOIN @F F ON F.Factura=R.Nota_Venta;
SELECT '04_TRIGGERS_DOCUMENTOS' Seccion,T.name,T.is_disabled
FROM sys.triggers T WHERE T.parent_id IN
 (OBJECT_ID('T3.CFDI_DOCUMENTOS'),OBJECT_ID('T3.CFDI_DOCUMENTOS_ENVIAR'));
IF OBJECT_ID('T3.RF_DOCUMENTOS','U') IS NOT NULL
 EXEC sys.sp_executesql N'SELECT ''05_REPOSITORIO_FISCAL'' Seccion,Factura,Anexo_CFD
 FROM T3.RF_DOCUMENTOS WHERE Factura IN
 (''1658507150'',''1658507151'',''1658516300'',''1658516520'',''1658520040'',''1658520050'');';

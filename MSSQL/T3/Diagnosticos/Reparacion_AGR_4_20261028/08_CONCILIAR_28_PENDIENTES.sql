DECLARE @Consulta int=1,@Asignacion varchar(30),@Primera bit;
DECLARE ListaAsignaciones CURSOR LOCAL STATIC READ_ONLY FOR
 SELECT Asignacion_ID FROM #A28 ORDER BY Asignacion_ID;
WHILE @Consulta<=4
BEGIN
 PRINT 'WITH K AS (';
 SET @Primera=1;
 OPEN ListaAsignaciones;
 FETCH NEXT FROM ListaAsignaciones INTO @Asignacion;
 WHILE @@FETCH_STATUS=0
 BEGIN
  IF @Primera=0 PRINT 'UNION ALL';
  PRINT 'SELECT '''+REPLACE(@Asignacion,'''','''''')+''' AS ASIGNACION_ID FROM DUAL';
  SET @Primera=0;
  FETCH NEXT FROM ListaAsignaciones INTO @Asignacion;
 END;
 CLOSE ListaAsignaciones;
 PRINT ')';
 IF @Consulta=1
 BEGIN
  PRINT 'SELECT JSON_OBJECT(''SECCION'' VALUE ''RELACIONES_ORIGINALES'',''FILA'' VALUE JSON_OBJECT(P.* RETURNING CLOB) FORMAT JSON RETURNING CLOB)';
  PRINT 'FROM T3.CFDI_AGRUPACION_PAGO P WHERE EXISTS(SELECT 1 FROM K WHERE K.ASIGNACION_ID=P.ASIGNACION_ID);';
 END;
 IF @Consulta=2
 BEGIN
  PRINT 'SELECT JSON_OBJECT(''SECCION'' VALUE ''CONTROLES_ORIGINALES'',''FILA'' VALUE JSON_OBJECT(A.* RETURNING CLOB) FORMAT JSON RETURNING CLOB)';
  PRINT 'FROM T3.CFDI_AGRUPACION_CTRL A WHERE EXISTS(SELECT 1 FROM T3.CFDI_AGRUPACION_PAGO P';
  PRINT 'JOIN K ON K.ASIGNACION_ID=P.ASIGNACION_ID WHERE P.AGRUPACION=A.AGRUPACION);';
 END;
 IF @Consulta=3
 BEGIN
  PRINT 'SELECT JSON_OBJECT(''SECCION'' VALUE ''COBRANZAS_ORIGINALES'',''FILA'' VALUE JSON_OBJECT(C.* RETURNING CLOB) FORMAT JSON RETURNING CLOB)';
  PRINT 'FROM T3.CFDI_COBRANZA C WHERE EXISTS(SELECT 1 FROM K WHERE K.ASIGNACION_ID=C.ASIGNACION_ID);';
 END;
 IF @Consulta=4
 BEGIN
  PRINT 'SELECT JSON_OBJECT(''SECCION'' VALUE ''DETALLE_COMPLETO_GRUPOS_ORIGINALES'',''FILA'' VALUE JSON_OBJECT(P.* RETURNING CLOB) FORMAT JSON RETURNING CLOB)';
  PRINT 'FROM T3.CFDI_AGRUPACION_PAGO P WHERE EXISTS(SELECT 1 FROM T3.CFDI_AGRUPACION_PAGO X';
  PRINT 'JOIN K ON K.ASIGNACION_ID=X.ASIGNACION_ID WHERE X.AGRUPACION=P.AGRUPACION);';
 END;
 SET @Consulta=@Consulta+1;
END;

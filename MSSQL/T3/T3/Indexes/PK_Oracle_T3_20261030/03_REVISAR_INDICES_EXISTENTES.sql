   Compara los indices existentes con las 81 claves del archivo Oracle.
   NULL en @SoloTabla incluye todas; el resultado muestra tambien otros
   indices de cada tabla para no ocultar una PK o clave con nombre distinto.
   Coincidir en nombre o columnas no convierte un indice en restriccion PK.
   ColumnasNullable es un conteo de definiciones NULL, no de filas con NULL.
   No prueba unicidad de los datos cuando el indice no es unico.
*/

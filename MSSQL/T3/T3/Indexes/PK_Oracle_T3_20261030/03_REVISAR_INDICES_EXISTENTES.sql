SELECT @@SERVERNAME Servidor,DB_NAME() BaseDatos,GETDATE() Captura;

SELECT E.Tabla,E.NombreOracle PKOracle,E.ColumnasOracle,
       I.name IndiceActual,I.type_desc TipoIndice,I.is_unique EsUnico,
       I.is_primary_key EsPrimaryKey,I.is_unique_constraint EsRestriccionUnique,
       I.is_disabled Deshabilitado,I.is_hypothetical Hipotetico,
       I.has_filter EsFiltrado,I.filter_definition Filtro,
       A.ColumnasClaveActuales,A.OrdenClaveActual,
       N.ColumnasNullable,F.FKReferenciandoIndice,
       CASE WHEN I.name COLLATE DATABASE_DEFAULT=E.NombreOracle THEN 1 ELSE 0 END MismoNombre,
       CASE WHEN A.ColumnasClaveActuales COLLATE DATABASE_DEFAULT=E.ColumnasOracle THEN 1 ELSE 0 END MismasColumnasYOrden,
       CASE WHEN T.object_id IS NULL THEN 'TABLA AUSENTE O NO VISIBLE'
            WHEN I.index_id IS NULL THEN 'SIN INDICES'
            WHEN I.is_primary_key=1 AND A.ColumnasClaveActuales COLLATE DATABASE_DEFAULT=E.ColumnasOracle THEN 'PK EQUIVALENTE; REVISAR ESTADO'
            WHEN I.is_primary_key=1 THEN 'PK EXISTENTE DIFERENTE'
            WHEN A.ColumnasClaveActuales COLLATE DATABASE_DEFAULT=E.ColumnasOracle THEN
                CASE WHEN I.is_disabled=1 OR I.is_hypothetical=1 THEN 'COLUMNAS COINCIDEN; INDICE NO ACTIVO'
                     WHEN I.has_filter=1 THEN 'COLUMNAS COINCIDEN; INDICE FILTRADO'
                     WHEN I.is_unique_constraint=1 THEN 'RESTRICCION UNIQUE COINCIDENTE; NO ES PK'
                     WHEN I.is_unique=1 THEN 'INDICE UNICO COINCIDENTE; NO ES PK'
                     ELSE 'INDICE NO UNICO COINCIDENTE; NO ES PK' END
            WHEN I.name COLLATE DATABASE_DEFAULT=E.NombreOracle THEN 'NOMBRE COINCIDE; COLUMNAS DIFERENTES'
            ELSE 'OTRO INDICE DE LA TABLA' END Diagnostico
FROM @Esperadas E
LEFT JOIN sys.tables T ON T.schema_id=SCHEMA_ID('T3') AND T.name COLLATE DATABASE_DEFAULT=E.Tabla
LEFT JOIN sys.indexes I ON I.object_id=T.object_id AND I.index_id>0
OUTER APPLY(
    SELECT STUFF((SELECT N','+QUOTENAME(C.name)
        FROM sys.index_columns IC JOIN sys.columns C ON C.object_id=IC.object_id AND C.column_id=IC.column_id
        WHERE IC.object_id=T.object_id AND IC.index_id=I.index_id AND IC.key_ordinal>0
        ORDER BY IC.key_ordinal FOR XML PATH(''),TYPE).value('.','nvarchar(max)'),1,1,N'') ColumnasClaveActuales,
    STUFF((SELECT N','+QUOTENAME(C.name)+CASE WHEN IC.is_descending_key=1 THEN N' DESC' ELSE N' ASC' END
        FROM sys.index_columns IC JOIN sys.columns C ON C.object_id=IC.object_id AND C.column_id=IC.column_id
        WHERE IC.object_id=T.object_id AND IC.index_id=I.index_id AND IC.key_ordinal>0
        ORDER BY IC.key_ordinal FOR XML PATH(''),TYPE).value('.','nvarchar(max)'),1,1,N'') OrdenClaveActual
) A
OUTER APPLY(
    SELECT COUNT(*) ColumnasNullable FROM sys.index_columns IC
    JOIN sys.columns C ON C.object_id=IC.object_id AND C.column_id=IC.column_id
    WHERE IC.object_id=T.object_id AND IC.index_id=I.index_id AND IC.key_ordinal>0 AND C.is_nullable=1
) N
OUTER APPLY(
    SELECT COUNT(*) FKReferenciandoIndice FROM sys.foreign_keys K
    WHERE K.referenced_object_id=T.object_id AND K.key_index_id=I.index_id
) F
WHERE @SoloTabla IS NULL OR E.Tabla=@SoloTabla
ORDER BY E.Tabla,
    CASE WHEN I.name COLLATE DATABASE_DEFAULT=E.NombreOracle THEN 0 ELSE 1 END,
    I.is_primary_key DESC,I.index_id;

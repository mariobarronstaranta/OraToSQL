;WITH TablasOracle AS (
 SELECT Tabla,NombrePK,COUNT(*) ColumnasClave FROM @Origen GROUP BY Tabla,NombrePK
), Volumen AS (
 -- Una fila por particion antes de sumar: evita multiplicar el conteo de
 -- filas al considerar las unidades IN_ROW, LOB y ROW_OVERFLOW.
 SELECT P.object_id,
 SUM(CASE WHEN P.index_id IN(0,1) THEN P.rows ELSE CONVERT(bigint,0) END) FilasAprox,
 SUM(CASE WHEN P.index_id IN(0,1) THEN A.Usadas ELSE CONVERT(bigint,0) END) PaginasTabla,
 SUM(CASE WHEN P.index_id>1 THEN A.Usadas ELSE CONVERT(bigint,0) END) PaginasIndices,
 SUM(A.Reservadas) PaginasReservadas
 FROM sys.partitions P
 OUTER APPLY (
   SELECT SUM(AU.used_pages) Usadas,SUM(AU.total_pages) Reservadas
   FROM sys.allocation_units AU
   WHERE (AU.type IN(1,3) AND AU.container_id=P.hobt_id)
      OR (AU.type=2 AND AU.container_id=P.partition_id)
 ) A
 WHERE P.object_id IN(SELECT T.object_id FROM sys.tables T
   JOIN TablasOracle O ON O.Tabla=T.name COLLATE DATABASE_DEFAULT
   WHERE T.schema_id=SCHEMA_ID(N'T3'))
 GROUP BY P.object_id
)
SELECT O.Tabla,O.NombrePK,
 CASE WHEN T.object_id IS NULL THEN 'OMITIDA_NO_VISIBLE'
      WHEN O.Tabla IN(N'CFDI_CATALOGOS_SAT',N'MOV_CLIENTE',N'USUARIOS') THEN 'PENDIENTE_DATOS'
      WHEN K.name IS NOT NULL THEN 'YA_TIENE_PK_REVISAR'
      WHEN V.FilasAprox IS NULL THEN 'SIN_METADATOS_VOLUMEN'
      ELSE 'CANDIDATA' END Estado,
 V.FilasAprox,
 CONVERT(decimal(19,2),V.PaginasTabla/128.0) MBTablaUsados,
 CONVERT(decimal(19,2),V.PaginasIndices/128.0) MBOtrosIndicesUsados,
 CONVERT(decimal(19,2),V.PaginasReservadas/128.0) MBTotalReservados,
 O.ColumnasClave,N.ColumnasClaveNullable,N.BytesDeclaradosClave,
 I.name IndiceHomonimo,I.type_desc TipoIndiceHomonimo,
 I.is_unique IndiceUnico,I.is_disabled IndiceDeshabilitado,
 CONVERT(decimal(19,2),IP.Paginas/128.0) MBIndiceHomonimo,
 K.name PKActual
INTO #OrdenPKT3
FROM TablasOracle O
LEFT JOIN sys.tables T ON T.schema_id=SCHEMA_ID(N'T3') AND T.name=O.Tabla COLLATE DATABASE_DEFAULT
LEFT JOIN Volumen V ON V.object_id=T.object_id
LEFT JOIN sys.indexes I ON I.object_id=T.object_id AND I.name=O.NombrePK COLLATE DATABASE_DEFAULT
LEFT JOIN sys.key_constraints K ON K.parent_object_id=T.object_id AND K.type='PK'
OUTER APPLY (
 SELECT SUM(CONVERT(int,C.is_nullable)) ColumnasClaveNullable,
        SUM(CONVERT(bigint,C.max_length)) BytesDeclaradosClave
 FROM @Origen OC JOIN sys.columns C ON C.object_id=T.object_id AND C.name=OC.Columna COLLATE DATABASE_DEFAULT
 WHERE OC.Tabla=O.Tabla
) N
OUTER APPLY (
 SELECT SUM(AU.used_pages) Paginas FROM sys.partitions P
 JOIN sys.allocation_units AU ON
   (AU.type IN(1,3) AND AU.container_id=P.hobt_id)
   OR (AU.type=2 AND AU.container_id=P.partition_id)
 WHERE P.object_id=I.object_id AND P.index_id=I.index_id
) IP;

-- Primero candidatas, de menor a mayor volumen; pendientes al final.
SELECT CASE WHEN Estado='CANDIDATA' THEN
 ROW_NUMBER() OVER(PARTITION BY Estado ORDER BY MBTablaUsados,FilasAprox,Tabla)
 END OrdenSugerido,*
FROM #OrdenPKT3
ORDER BY CASE WHEN Estado='CANDIDATA' THEN 0 ELSE 1 END,
 Estado,MBTablaUsados,FilasAprox,Tabla;

SELECT Estado,COUNT(*) Tablas,SUM(FilasAprox) FilasAprox,
 SUM(MBTablaUsados) MBTablaUsados,SUM(MBTotalReservados) MBTotalReservados
FROM #OrdenPKT3 GROUP BY Estado ORDER BY Estado;
DROP TABLE #OrdenPKT3;

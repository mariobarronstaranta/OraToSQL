DECLARE @Resultado table(
 Tabla sysname,NombrePK sysname,ColumnasOracle nvarchar(max),
 Estado varchar(40),ColumnasNullable int NULL,FilasConNull bigint NULL,
 GruposDuplicados bigint NULL,Observacion nvarchar(2000),SQLDiagnostico nvarchar(max));
DECLARE @Tabla sysname,@PK sysname,@Objeto int,@Nombre nvarchar(520),
 @Columnas nvarchar(max),@Predicado nvarchar(max),@SQL nvarchar(max),
 @Diagnostico nvarchar(max),@N bigint,@D bigint,@Nullable int;
DECLARE Claves CURSOR LOCAL STATIC READ_ONLY FOR
SELECT Tabla,NombrePK FROM @Origen WHERE @SoloTabla IS NULL OR Tabla=@SoloTabla GROUP BY Tabla,NombrePK ORDER BY Tabla;
OPEN Claves;
FETCH NEXT FROM Claves INTO @Tabla,@PK;
WHILE @@FETCH_STATUS=0
BEGIN
 SET @Nombre=QUOTENAME(N'T3')+N'.'+QUOTENAME(@Tabla);
 SET @Objeto=OBJECT_ID(@Nombre,N'U');
 SELECT @Columnas=STUFF((SELECT N','+QUOTENAME(Columna) FROM @Origen WHERE Tabla=@Tabla
   ORDER BY Posicion FOR XML PATH(''),TYPE).value('.','nvarchar(max)'),1,1,N''),
 @Predicado=STUFF((SELECT N' OR '+QUOTENAME(Columna)+N' IS NULL' FROM @Origen WHERE Tabla=@Tabla
   ORDER BY Posicion FOR XML PATH(''),TYPE).value('.','nvarchar(max)'),1,4,N'');
 SET @N=NULL; SET @D=NULL; SET @Nullable=NULL; SET @Diagnostico=NULL;
 BEGIN TRY
  IF @Objeto IS NULL
   INSERT @Resultado VALUES(@Tabla,@PK,@Columnas,'OMITIDA_NO_VISIBLE',NULL,NULL,NULL,
     N'Tabla ausente o sin visibilidad de metadatos. No se propone crearla.',NULL);
  ELSE
  BEGIN
   IF (SELECT COUNT(*) FROM sys.columns C JOIN @Origen O ON O.Tabla=@Tabla
       AND O.Columna=C.name COLLATE DATABASE_DEFAULT WHERE C.object_id=@Objeto)
       <> (SELECT COUNT(*) FROM @Origen WHERE Tabla=@Tabla)
      THROW 56811,'Faltan columnas de la clave Oracle.',1;
   SELECT @Nullable=SUM(CONVERT(int,C.is_nullable)) FROM sys.columns C
     JOIN @Origen O ON O.Tabla=@Tabla AND O.Columna=C.name COLLATE DATABASE_DEFAULT WHERE C.object_id=@Objeto;
   SET @Diagnostico=N'SELECT TOP(20) '+@Columnas+N' FROM '+@Nombre+N' WHERE '+@Predicado+N';'+CHAR(13)+CHAR(10)+
       N'SELECT TOP(20) '+@Columnas+N',COUNT_BIG(*) Repeticiones FROM '+@Nombre+
       N' GROUP BY '+@Columnas+N' HAVING COUNT_BIG(*)>1 ORDER BY Repeticiones DESC;';
   SET @SQL=N'SELECT @N=COUNT_BIG(*) FROM '+@Nombre+N' WHERE '+@Predicado+N';'+
       N'SELECT @D=COUNT_BIG(*) FROM (SELECT 1 X FROM '+@Nombre+N' GROUP BY '+@Columnas+N' HAVING COUNT_BIG(*)>1) G;';
   EXEC sys.sp_executesql @SQL,N'@N bigint OUTPUT,@D bigint OUTPUT',@N=@N OUTPUT,@D=@D OUTPUT;
   INSERT @Resultado VALUES(@Tabla,@PK,@Columnas,
       CASE WHEN @N>0 OR @D>0 THEN 'BLOQUEADA_DATOS' ELSE 'DATOS_VALIDOS' END,@Nullable,@N,@D,
       CASE WHEN @N>0 OR @D>0 THEN N'Resolver NULL/duplicados antes de crear PK. No se modificaron registros.'
       ELSE N'Datos compatibles en esta captura; falta evaluar DDL, dependencias y propiedades fisicas.' END,@Diagnostico);
  END;
 END TRY
 BEGIN CATCH
  INSERT @Resultado VALUES(@Tabla,@PK,@Columnas,'ERROR_REVISION',@Nullable,@N,@D,
      LEFT(CONCAT(ERROR_NUMBER(),N': ',ERROR_MESSAGE()),2000),@Diagnostico);
 END CATCH;
 FETCH NEXT FROM Claves INTO @Tabla,@PK;
END;
CLOSE Claves; DEALLOCATE Claves;
SELECT '01_DATOS' Seccion,* FROM @Resultado ORDER BY Tabla;
SELECT '02_RESUMEN' Seccion,Estado,COUNT(*) Tablas FROM @Resultado GROUP BY Estado;

-- Propiedades no incluidas en el reporte 03: INCLUDE, almacenamiento,
-- compresion y opciones. Revisarlas antes de reemplazar un indice existente.
SELECT '03_PROPIEDADES_INDICE' Seccion,R.Tabla,R.NombrePK,I.name Indice,
 I.type_desc,I.is_unique,I.is_primary_key,I.is_unique_constraint,
 I.is_disabled,I.is_hypothetical,I.has_filter,I.filter_definition,
 I.fill_factor,I.is_padded,I.ignore_dup_key,I.allow_row_locks,I.allow_page_locks,
 DS.name EspacioDatos,DS.type_desc TipoEspacioDatos,P.partition_number,P.data_compression_desc,
 S.no_recompute,S.is_incremental,
 IC.key_ordinal,IC.is_included_column,IC.is_descending_key,IC.partition_ordinal,
 C.name Columna,C.is_nullable,
 (SELECT COUNT(*) FROM sys.foreign_keys F WHERE F.referenced_object_id=I.object_id
   AND F.key_index_id=I.index_id) FKReferenciandoIndice
FROM @Resultado R
JOIN sys.tables T ON T.schema_id=SCHEMA_ID(N'T3') AND T.name=R.Tabla COLLATE DATABASE_DEFAULT
JOIN sys.indexes I ON I.object_id=T.object_id AND I.name=R.NombrePK COLLATE DATABASE_DEFAULT
LEFT JOIN sys.data_spaces DS ON DS.data_space_id=I.data_space_id
LEFT JOIN sys.partitions P ON P.object_id=I.object_id AND P.index_id=I.index_id
LEFT JOIN sys.stats S ON S.object_id=I.object_id AND S.stats_id=I.index_id
LEFT JOIN sys.index_columns IC ON IC.object_id=I.object_id AND IC.index_id=I.index_id
LEFT JOIN sys.columns C ON C.object_id=IC.object_id AND C.column_id=IC.column_id
ORDER BY R.Tabla,P.partition_number,IC.index_column_id;
-- XML evita perder el texto de consultas largas por truncamiento del grid.
SELECT Tabla,SQLDiagnostico FROM @Resultado WHERE Estado IN ('BLOQUEADA_DATOS','ERROR_REVISION')
FOR XML PATH('Tabla'),ROOT('ConsultasDiagnostico'),TYPE;

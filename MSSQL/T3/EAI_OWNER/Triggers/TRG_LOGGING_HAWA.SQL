/* Origen: ORA/T3/EAI_OWNER/Triggers/TRG_LOGGING_HAWA.SQL
   Requiere 00_AUDIT_ROW_ID.SQL. Procesa todas las filas por sentencia.
   Usuario_Red usa ORIGINAL_LOGIN(); no identifica el OS_USER de clientes SQL.
*/
CREATE OR ALTER TRIGGER [EAI_OWNER].[TRG_LOGGING_HAWA]
ON [EAI_OWNER].[MX_CFG_CONDITION_HAWA]
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO [EAI_OWNER].[MX_CONDITION_HAWA_LOG]
        ([FECHA], [USUARIO], [ACTION], [USUARIO_RED], [IP], [TERMINAL], [NEW_LP], [NEW_SKU], [NEW_COND], [OLD_LP], [OLD_SKU], [OLD_COND])
    SELECT
        SYSDATETIME(), CONVERT(varchar(30), SUSER_SNAME()),
        CASE WHEN d.[AUDIT_ROW_ID] IS NULL THEN 'Insert'
             WHEN i.[AUDIT_ROW_ID] IS NULL THEN 'Delete' ELSE 'Update' END,
        CONVERT(varchar(30), ORIGINAL_LOGIN()),
        CONVERT(varchar(30), CONNECTIONPROPERTY('client_net_address')),
        CONVERT(varchar(40), HOST_NAME()),
        CASE WHEN DATALENGTH(i.[LP]) = 0 THEN NULL ELSE i.[LP] END,
        CASE WHEN DATALENGTH(i.[SKU]) = 0 THEN NULL ELSE i.[SKU] END,
        CASE WHEN DATALENGTH(i.[COND]) = 0 THEN NULL ELSE i.[COND] END,
        CASE WHEN DATALENGTH(d.[LP]) = 0 THEN NULL ELSE d.[LP] END,
        CASE WHEN DATALENGTH(d.[SKU]) = 0 THEN NULL ELSE d.[SKU] END,
        CASE WHEN DATALENGTH(d.[COND]) = 0 THEN NULL ELSE d.[COND] END
    FROM inserted AS i
    FULL OUTER JOIN deleted AS d ON d.[AUDIT_ROW_ID] = i.[AUDIT_ROW_ID];
END;
GO

/* Origen: ORA/T3/EAI_OWNER/Triggers/TRG_XP_ASIGNACION_PAGO.SQL
   Requiere 00_AUDIT_ROW_ID.SQL. Procesa todas las filas por sentencia.
   Usuario_Red usa ORIGINAL_LOGIN(); no identifica el OS_USER de clientes SQL.
*/
CREATE OR ALTER TRIGGER [EAI_OWNER].[TRG_XP_ASIGNACION_PAGO]
ON [EAI_OWNER].[XP_ASIGNACION_PAGO]
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    -- Solo se registran los campos que cambian, como en Oracle.
    INSERT INTO [EAI_OWNER].[WA_COBRANZA_LOG]
        ([FECHA], [USUARIO], [ACTION], [USUARIO_RED], [IP], [TERMINAL], [TIPO_WA], [OLD_FACTURA], [OLD_NOTA_CREDITO], [OLD_IMPORTE], [OLD_FECHA_ASIGNACION], [OLD_CLEARING], [NEW_FACTURA], [NEW_NOTA_CREDITO], [NEW_IMPORTE], [NEW_FECHA_ASIGNACION], [NEW_CLEARING])
    SELECT
        SYSDATETIME(), CONVERT(varchar(30), SUSER_SNAME()),
        CASE WHEN d.[AUDIT_ROW_ID] IS NULL THEN 'Insert'
             WHEN i.[AUDIT_ROW_ID] IS NULL THEN 'Delete' ELSE 'Update' END,
        CONVERT(varchar(30), ORIGINAL_LOGIN()),
        CONVERT(varchar(30), CONNECTIONPROPERTY('client_net_address')),
        CONVERT(varchar(40), HOST_NAME()),
        'Cobza',
        CASE WHEN CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(i.[FACTURA]) = 0 THEN NULL ELSE i.[FACTURA] END, 'NULO')) <> CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(d.[FACTURA]) = 0 THEN NULL ELSE d.[FACTURA] END, 'NULO'))
             THEN CASE WHEN DATALENGTH(d.[FACTURA]) = 0 THEN NULL ELSE d.[FACTURA] END END,
        NULL,
        CASE WHEN ISNULL(i.[IMPORTE], 0) <> ISNULL(d.[IMPORTE], 0)
             THEN d.[IMPORTE] END,
        CASE WHEN CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(i.[FECHA_ASIGNACION]) = 0 THEN NULL ELSE i.[FECHA_ASIGNACION] END, 'NULO')) <> CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(d.[FECHA_ASIGNACION]) = 0 THEN NULL ELSE d.[FECHA_ASIGNACION] END, 'NULO'))
             THEN CASE WHEN DATALENGTH(d.[FECHA_ASIGNACION]) = 0 THEN NULL ELSE d.[FECHA_ASIGNACION] END END,
        CASE WHEN CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(i.[CLEARING_DOCUMENT]) = 0 THEN NULL ELSE i.[CLEARING_DOCUMENT] END, 'NULO')) <> CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(d.[CLEARING_DOCUMENT]) = 0 THEN NULL ELSE d.[CLEARING_DOCUMENT] END, 'NULO'))
             THEN CASE WHEN DATALENGTH(d.[CLEARING_DOCUMENT]) = 0 THEN NULL ELSE d.[CLEARING_DOCUMENT] END END,
        CASE WHEN CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(i.[FACTURA]) = 0 THEN NULL ELSE i.[FACTURA] END, 'NULO')) <> CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(d.[FACTURA]) = 0 THEN NULL ELSE d.[FACTURA] END, 'NULO'))
             THEN CASE WHEN DATALENGTH(i.[FACTURA]) = 0 THEN NULL ELSE i.[FACTURA] END END,
        NULL,
        CASE WHEN ISNULL(i.[IMPORTE], 0) <> ISNULL(d.[IMPORTE], 0)
             THEN i.[IMPORTE] END,
        CASE WHEN CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(i.[FECHA_ASIGNACION]) = 0 THEN NULL ELSE i.[FECHA_ASIGNACION] END, 'NULO')) <> CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(d.[FECHA_ASIGNACION]) = 0 THEN NULL ELSE d.[FECHA_ASIGNACION] END, 'NULO'))
             THEN CASE WHEN DATALENGTH(i.[FECHA_ASIGNACION]) = 0 THEN NULL ELSE i.[FECHA_ASIGNACION] END END,
        CASE WHEN CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(i.[CLEARING_DOCUMENT]) = 0 THEN NULL ELSE i.[CLEARING_DOCUMENT] END, 'NULO')) <> CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(d.[CLEARING_DOCUMENT]) = 0 THEN NULL ELSE d.[CLEARING_DOCUMENT] END, 'NULO'))
             THEN CASE WHEN DATALENGTH(i.[CLEARING_DOCUMENT]) = 0 THEN NULL ELSE i.[CLEARING_DOCUMENT] END END
    FROM inserted AS i
    FULL OUTER JOIN deleted AS d ON d.[AUDIT_ROW_ID] = i.[AUDIT_ROW_ID]
    WHERE i.[AUDIT_ROW_ID] IS NULL OR d.[AUDIT_ROW_ID] IS NULL
       OR CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(i.[FACTURA]) = 0 THEN NULL ELSE i.[FACTURA] END, 'NULO')) <> CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(d.[FACTURA]) = 0 THEN NULL ELSE d.[FACTURA] END, 'NULO'))
       OR ISNULL(i.[IMPORTE], 0) <> ISNULL(d.[IMPORTE], 0)
       OR CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(i.[FECHA_ASIGNACION]) = 0 THEN NULL ELSE i.[FECHA_ASIGNACION] END, 'NULO')) <> CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(d.[FECHA_ASIGNACION]) = 0 THEN NULL ELSE d.[FECHA_ASIGNACION] END, 'NULO'))
       OR CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(i.[CLEARING_DOCUMENT]) = 0 THEN NULL ELSE i.[CLEARING_DOCUMENT] END, 'NULO')) <> CONVERT(varbinary(max), ISNULL(CASE WHEN DATALENGTH(d.[CLEARING_DOCUMENT]) = 0 THEN NULL ELSE d.[CLEARING_DOCUMENT] END, 'NULO'));
END;
GO

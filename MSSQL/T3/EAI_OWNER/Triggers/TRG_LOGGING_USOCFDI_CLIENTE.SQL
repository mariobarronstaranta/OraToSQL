/* Origen: ORA/T3/EAI_OWNER/Triggers/TRG_LOGGING_USOCFDI_CLIENTE.SQL
   Requiere 00_AUDIT_ROW_ID.SQL. Procesa todas las filas por sentencia.
   Usuario_Red usa ORIGINAL_LOGIN(); no identifica el OS_USER de clientes SQL.
   El trigger pertenece a T3 porque SQL Server exige el esquema de la tabla.
*/
CREATE OR ALTER TRIGGER [T3].[TRG_LOGGING_USOCFDI_CLIENTE]
ON [T3].[CFDI_USOCFDI_CLIENTE]
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO [EAI_OWNER].[MX_USOCFDI_CLIENTE_LOG]
        ([FECHA], [USUARIO], [ACTION], [USUARIO_RED], [IP], [TERMINAL], [NEW_CLIENTE], [NEW_USO_VTA], [NEW_USO_DEV], [OLD_CLIENTE], [OLD_USO_VTA], [OLD_USO_DEV])
    SELECT
        SYSDATETIME(), CONVERT(varchar(30), SUSER_SNAME()),
        CASE WHEN d.[AUDIT_ROW_ID] IS NULL THEN 'Insert'
             WHEN i.[AUDIT_ROW_ID] IS NULL THEN 'Delete' ELSE 'Update' END,
        CONVERT(varchar(30), ORIGINAL_LOGIN()),
        CONVERT(varchar(30), CONNECTIONPROPERTY('client_net_address')),
        CONVERT(varchar(40), HOST_NAME()),
        CASE WHEN DATALENGTH(i.[CLIENTE_SAP]) = 0 THEN NULL ELSE i.[CLIENTE_SAP] END,
        CASE WHEN DATALENGTH(i.[USO_VENTA]) = 0 THEN NULL ELSE i.[USO_VENTA] END,
        CASE WHEN DATALENGTH(i.[USO_DEVOLUCION]) = 0 THEN NULL ELSE i.[USO_DEVOLUCION] END,
        CASE WHEN DATALENGTH(d.[CLIENTE_SAP]) = 0 THEN NULL ELSE d.[CLIENTE_SAP] END,
        CASE WHEN DATALENGTH(d.[USO_VENTA]) = 0 THEN NULL ELSE d.[USO_VENTA] END,
        CASE WHEN DATALENGTH(d.[USO_DEVOLUCION]) = 0 THEN NULL ELSE d.[USO_DEVOLUCION] END
    FROM inserted AS i
    FULL OUTER JOIN deleted AS d ON d.[AUDIT_ROW_ID] = i.[AUDIT_ROW_ID];
END;
GO

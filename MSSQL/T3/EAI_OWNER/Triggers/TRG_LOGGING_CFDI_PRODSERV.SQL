/* Origen: ORA/T3/EAI_OWNER/Triggers/TRG_LOGGING_CFDI_PRODSERV.SQL
   Requiere 00_AUDIT_ROW_ID.SQL. Procesa todas las filas por sentencia.
   Usuario_Red usa ORIGINAL_LOGIN(); no identifica el OS_USER de clientes SQL.
   El trigger pertenece a T3 porque SQL Server exige el esquema de la tabla.
*/
CREATE OR ALTER TRIGGER [T3].[TRG_LOGGING_CFDI_PRODSERV]
ON [T3].[CFDI_PRODSERV]
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO [EAI_OWNER].[MX_CFDI_PRODSERV_LOG]
        ([FECHA], [USUARIO], [ACTION], [USUARIO_RED], [IP], [TERMINAL], [NEW_MODULO], [NEW_MATERIAL], [NEW_NOMBREMATERIAL], [NEW_UNIDADMEDIDA], [NEW_SAT_CLAVE], [NEW_SAT_UNIDADMEDIDA], [OLD_MODULO], [OLD_MATERIAL], [OLD_NOMBREMATERIAL], [OLD_UNIDADMEDIDA], [OLD_SAT_CLAVE], [OLD_SAT_UNIDADMEDIDA])
    SELECT
        SYSDATETIME(), CONVERT(varchar(30), SUSER_SNAME()),
        CASE WHEN d.[AUDIT_ROW_ID] IS NULL THEN 'Insert'
             WHEN i.[AUDIT_ROW_ID] IS NULL THEN 'Delete' ELSE 'Update' END,
        CONVERT(varchar(30), ORIGINAL_LOGIN()),
        CONVERT(varchar(30), CONNECTIONPROPERTY('client_net_address')),
        CONVERT(varchar(40), HOST_NAME()),
        CASE WHEN DATALENGTH(i.[MODULO]) = 0 THEN NULL ELSE i.[MODULO] END,
        CASE WHEN DATALENGTH(i.[MATERIAL]) = 0 THEN NULL ELSE i.[MATERIAL] END,
        CASE WHEN DATALENGTH(i.[NOMBREMATERIAL]) = 0 THEN NULL ELSE i.[NOMBREMATERIAL] END,
        CASE WHEN DATALENGTH(i.[UNIDADMEDIDA]) = 0 THEN NULL ELSE i.[UNIDADMEDIDA] END,
        CASE WHEN DATALENGTH(i.[SAT_CLAVE]) = 0 THEN NULL ELSE i.[SAT_CLAVE] END,
        CASE WHEN DATALENGTH(i.[SAT_UNIDADMEDIDA]) = 0 THEN NULL ELSE i.[SAT_UNIDADMEDIDA] END,
        CASE WHEN DATALENGTH(d.[MODULO]) = 0 THEN NULL ELSE d.[MODULO] END,
        CASE WHEN DATALENGTH(d.[MATERIAL]) = 0 THEN NULL ELSE d.[MATERIAL] END,
        CASE WHEN DATALENGTH(d.[NOMBREMATERIAL]) = 0 THEN NULL ELSE d.[NOMBREMATERIAL] END,
        CASE WHEN DATALENGTH(d.[UNIDADMEDIDA]) = 0 THEN NULL ELSE d.[UNIDADMEDIDA] END,
        CASE WHEN DATALENGTH(d.[SAT_CLAVE]) = 0 THEN NULL ELSE d.[SAT_CLAVE] END,
        CASE WHEN DATALENGTH(d.[SAT_UNIDADMEDIDA]) = 0 THEN NULL ELSE d.[SAT_UNIDADMEDIDA] END
    FROM inserted AS i
    FULL OUTER JOIN deleted AS d ON d.[AUDIT_ROW_ID] = i.[AUDIT_ROW_ID];
END;
GO

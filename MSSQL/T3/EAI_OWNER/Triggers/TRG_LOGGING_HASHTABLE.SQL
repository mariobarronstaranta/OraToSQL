/* Origen: ORA/T3/EAI_OWNER/Triggers/TRG_LOGGING_HASHTABLE.SQL
   Requiere 00_AUDIT_ROW_ID.SQL. Procesa todas las filas por sentencia.
   Usuario_Red usa ORIGINAL_LOGIN(); no identifica el OS_USER de clientes SQL.
*/
CREATE OR ALTER TRIGGER [EAI_OWNER].[TRG_LOGGING_HASHTABLE]
ON [EAI_OWNER].[MX_HASHTABLE]
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO [EAI_OWNER].[MX_HASHTABLE_LOG]
        ([FECHA], [USUARIO], [ACTION], [USUARIO_RED], [IP], [TERMINAL], [NEW_TYPE], [NEW_SOURCE], [NEW_TARGET], [OLD_TYPE], [OLD_SOURCE], [OLD_TARGET])
    SELECT
        SYSDATETIME(), CONVERT(varchar(30), SUSER_SNAME()),
        CASE WHEN d.[AUDIT_ROW_ID] IS NULL THEN 'Insert'
             WHEN i.[AUDIT_ROW_ID] IS NULL THEN 'Delete' ELSE 'Update' END,
        CONVERT(varchar(30), ORIGINAL_LOGIN()),
        CONVERT(varchar(30), CONNECTIONPROPERTY('client_net_address')),
        CONVERT(varchar(40), HOST_NAME()),
        CASE WHEN DATALENGTH(i.[TYPE]) = 0 THEN NULL ELSE i.[TYPE] END,
        CASE WHEN DATALENGTH(i.[SOURCE]) = 0 THEN NULL ELSE i.[SOURCE] END,
        CASE WHEN DATALENGTH(i.[TARGET]) = 0 THEN NULL ELSE i.[TARGET] END,
        CASE WHEN DATALENGTH(d.[TYPE]) = 0 THEN NULL ELSE d.[TYPE] END,
        CASE WHEN DATALENGTH(d.[SOURCE]) = 0 THEN NULL ELSE d.[SOURCE] END,
        CASE WHEN DATALENGTH(d.[TARGET]) = 0 THEN NULL ELSE d.[TARGET] END
    FROM inserted AS i
    FULL OUTER JOIN deleted AS d ON d.[AUDIT_ROW_ID] = i.[AUDIT_ROW_ID];
END;
GO
